"""Generate fixed-build signatures and current expected KV; never load DLLs or touch runtime files."""
from pathlib import Path
import hashlib
import json
import re
import struct
import sys

PROJECT = Path(__file__).resolve().parent
ROOT = PROJECT.parents[3]
sys.path.insert(0, str(ROOT / 'DOTA2_PERFORMANCE/python-libs'))
import pefile

canonical_snapshot = ROOT / 'THDAmethyst_Game/scripts/vscripts/util/thd_bot_native_snapshot.lua'
(PROJECT / 'kv_snapshot.lua').write_bytes(canonical_snapshot.read_bytes())

layout = json.loads((PROJECT / 'signature_layout.json').read_text(encoding='utf-8'))
raw = Path(r'D:/DOTA Latest/dota 2 beta/game/dota/bin/win64/server.dll').read_bytes()
if hashlib.sha256(raw).hexdigest() != layout['engine_sha256']:
    raise SystemExit('Unsupported engine SHA-256; no files generated')
pe = pefile.PE(data=raw, fast_load=True)
classes = layout['classes']
getters = sorted({int(c['slot4'], 16) for c in classes})
if len(classes) != 51 or len(getters) != 12:
    raise SystemExit('Unexpected fixed-build class inventory')
for c in classes:
    pointer = struct.unpack('<Q', pe.get_data(int(c['vtable'], 16) + 32, 8))[0]
    if pointer != pe.OPTIONAL_HEADER.ImageBase + int(c['slot4'], 16):
        raise SystemExit('Vtable signature mismatch')

source = ROOT / 'THDAmethyst_Game/scripts/npc/bot_heroes_custom.txt'
source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
text = re.sub(r'//[^\n]*', '', source.read_text(encoding='utf-8-sig'))
entries = re.findall(r'"(npc_dota_hero_[^"]+)"\s*\{\s*"Bot"\s*\{\s*"AggressionFactor"\s*"([^"]+)"\s*"HeroType"\s*"([^"]+)"\s*\}\s*\}', text)
if len(entries) != 72 or len({e[0] for e in entries}) != 72:
    raise SystemExit('Expected 72 unique current R2 slot entries')
bits = {'TANK': 1, 'STUN_SUPPORT': 2, 'PURE_SUPPORT': 4, 'PUSH_SUPPORT': 8,
        'HARD_CARRY': 16, 'SEMI_CARRY': 32, 'GANKER': 64}
expected = []
for slot, value, tags in entries:
    tokens = [t.strip().removeprefix('DOTA_BOT_') for t in tags.split('|')]
    if len(tokens) != len(set(tokens)) or any(t not in bits for t in tokens):
        raise SystemExit('Unsupported HeroType: ' + slot)
    number = float(value)
    if number not in (0.95, 1.0, 1.05):
        raise SystemExit('Unexpected R2 base coefficient: ' + slot)
    expected.append({'slot': slot, 'base': number, 'mask': sum(bits[t] for t in tokens), 'hero_type': tags})

lines = ['// Generated by prepare_signatures.py from the fixed engine and current R2 source.',
         '#pragma once', 'namespace signatures {', f'inline constexpr char sourceSha[]="{source_hash}";',
         f'inline constexpr std::uintptr_t imageSize=0x{pe.OPTIONAL_HEADER.SizeOfImage:x};',
         'struct Getter { std::uintptr_t rva; std::array<unsigned char,16> bytes; };',
         'inline constexpr Getter getters[]={']
for address in getters:
    lines.append('{0x%x,{%s}},' % (address, ','.join('0x%02x' % b for b in pe.get_data(address, 16))))
lines += ['};', 'struct HeroClass { const char* name; std::uintptr_t vtable; std::size_t getter; };',
          'inline constexpr HeroClass classes[]={']
for c in classes:
    lines.append('{"%s",%s,%d},' % (c['class'].removeprefix('.?AV').removesuffix('@@'), c['vtable'], getters.index(int(c['slot4'], 16))))
lines += ['};', 'struct Expected { const char* slot; float base; std::uint32_t mask; };',
          'inline constexpr Expected expected[]={']
for entry in expected:
    lines.append('{"%s",%.2ff,%d},' % (entry['slot'], entry['base'], entry['mask']))
lines += ['};', '}']
(PROJECT / 'signatures.hpp').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(PROJECT / 'expected-kv.json').write_text(json.dumps({'source_sha256': source_hash, 'engine_sha256': layout['engine_sha256'], 'heroes': expected}, indent=2), encoding='utf-8')
print('Generated 51 class guards, 12 original getters and 72 expected slot records')
